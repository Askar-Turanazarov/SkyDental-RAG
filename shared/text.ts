/* ============================================================
   Лексическая нормализация: «основы» слов для RU и UZ.

   Основа — первые 5 букв слова. Это грубо, но для русских и
   узбекских словоформ на объёме одной клиники работает: «имплант»,
   «имплантация», «импланты» дают одну основу «импла». Используется
   и демо-ботом, и ключевым (BM25-подобным) плечом гибридного поиска
   на сервере, поэтому ведут они себя одинаково.
   ============================================================ */

/** Слова вопроса, которые ничего не говорят о теме. */
export const STOPWORDS = new Set([
  // ru
  'сколь', 'стоит', 'можно', 'какой', 'какая', 'какие', 'как', 'ли', 'вы', 'у', 'вас',
  'есть', 'нужно', 'надо', 'это', 'что', 'где', 'когда', 'правд', 'мне', 'для', 'при',
  // uz
  'qanch', 'turad', 'mumki', 'qanda', 'nima', 'bormi', 'kerak', 'uchun', 'bilan', 'rostd',
])

/** Основы слов, по которым видно, что человек спрашивает о цене. */
export const PRICE_WORDS = new Set(['сколь', 'стоит', 'цена', 'цены', 'стоим', 'прайс', 'qanch', 'turad', 'narx', 'narxi'])

export function stems(text: string): string[] {
  return (text.toLowerCase().match(/[\p{L}ʻʼ']+/gu) ?? [])
    .map((w) => w.replace(/[ʻʼ']/g, ''))
    .filter((w) => w.length >= 3)
    .map((w) => w.slice(0, 5))
}

/** Основы вопроса без стоп-слов и признак ценового вопроса. */
export function queryTerms(question: string): { terms: string[]; priceIntent: boolean } {
  const all = stems(question)
  return {
    terms: [...new Set(all.filter((w) => !STOPWORDS.has(w)))],
    priceIntent: all.some((w) => PRICE_WORDS.has(w)),
  }
}
